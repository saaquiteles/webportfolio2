import { describe, expect, it } from 'vitest';
import { render, screen, within } from '@testing-library/react';
import { caseStudies } from '#site/content';
import Page, { generateStaticParams } from './page';

describe('Case study page', () => {
  it('generates one static page per case study', () => {
    const params = generateStaticParams();

    expect(params).toEqual(
      expect.arrayContaining([{ slug: 'buriccat' }, { slug: 'cockatiel-recognition' }]),
    );
    expect(params).toHaveLength(caseStudies.length);
  });

  it('shows the title as the only h1, a main landmark and the body text', async () => {
    render(await Page({ params: Promise.resolve({ slug: 'buriccat' }) }));

    const headings = screen.getAllByRole('heading', { level: 1 });
    expect(headings).toHaveLength(1);
    expect(headings[0]).toHaveTextContent('Buriccat');
    expect(screen.getByRole('main')).toBeInTheDocument();
    expect(screen.getByText('A fun project to try out React Three Fiber.')).toBeInTheDocument();
  });

  it.each(caseStudies.map((study) => study.slug))('%s renders exactly one h1', async (slug) => {
    const { unmount } = render(await Page({ params: Promise.resolve({ slug }) }));

    expect(screen.getAllByRole('heading', { level: 1 })).toHaveLength(1);
    unmount();
  });

  it('shows the thesis with its paper link and names the co-authors', async () => {
    render(await Page({ params: Promise.resolve({ slug: 'cockatiel-recognition' }) }));

    expect(screen.getByRole('heading', { level: 1 })).toHaveTextContent(
      'A Vision System That Tells Cockatiels Apart',
    );
    expect(screen.getByRole('link', { name: 'Read the published paper' })).toHaveAttribute(
      'href',
      'https://ebooks.iospress.nl/doi/10.3233/ATDE251126',
    );
    const credits = screen.getByRole('heading', { level: 2, name: 'Credits' });
    expect(credits).toBeInTheDocument();
    const main = within(screen.getByRole('main'));
    expect(main.getByText(/Darryl Angelo O\. Narvaez/)).toBeInTheDocument();
    expect(main.getByText(/Cyrel O\. Manlises/)).toBeInTheDocument();
    expect(main.getByText(/91\.17% accuracy/)).toBeInTheDocument();
  });

  it('credits the third-party assets and AI-made parts of Buriccat', async () => {
    render(await Page({ params: Promise.resolve({ slug: 'buriccat' }) }));

    const main = within(screen.getByRole('main'));
    expect(main.getByRole('heading', { level: 2, name: 'Credits' })).toBeInTheDocument();
    const kenney = main.getByRole('link', { name: 'Kenney' });
    expect(kenney).toHaveAttribute('href', 'https://kenney.nl');
    expect(kenney.closest('li')).toHaveTextContent('CC0');
    const music = main.getByRole('link', { name: 'Casino Jazz by Pink Banana' });
    expect(music).toHaveAttribute('href', 'https://soundcloud.com/pinkbananamusic/casino-jazz-1');
    expect(music.closest('li')).toHaveTextContent('CC0');
    expect(main.getByText(/chip models were made by Claude/)).toBeInTheDocument();
    expect(main.getByText(/logo was generated by Gemini/)).toBeInTheDocument();
    expect(main.getByText(/speech synthesis/)).toBeInTheDocument();
  });

  it('describes how Buriccat is built and links to its repository', async () => {
    render(await Page({ params: Promise.resolve({ slug: 'buriccat' }) }));

    const main = within(screen.getByRole('main'));
    expect(
      main.getByText('React 19, Vite, React Three Fiber and GSAP, tested with Vitest.'),
    ).toBeInTheDocument();
    expect(main.getByRole('link', { name: 'Source code on GitHub' })).toHaveAttribute(
      'href',
      'https://github.com/saaquiteles/baccarat',
    );
  });

  it('shows the portfolio case study, its repository and the credit to Matt Pocock', async () => {
    render(await Page({ params: Promise.resolve({ slug: 'portfolio' }) }));

    expect(screen.getByRole('heading', { level: 1 })).toHaveTextContent('This portfolio');
    const main = within(screen.getByRole('main'));
    expect(main.getByRole('link', { name: 'Source code on GitHub' })).toHaveAttribute(
      'href',
      'https://github.com/saaquiteles/webportfolio2',
    );
    expect(main.getByRole('heading', { level: 2, name: 'Credits' })).toBeInTheDocument();
    expect(main.getByRole('link', { name: "Matt Pocock's skills" })).toHaveAttribute(
      'href',
      'https://github.com/mattpocock/skills',
    );
  });

  it('does not render a page for an unknown slug', async () => {
    await expect(Page({ params: Promise.resolve({ slug: 'does-not-exist' }) })).rejects.toThrow(
      'NEXT_HTTP_ERROR_FALLBACK;404',
    );
  });
});
